/// Writes the tables `TextPainter` measures a font of the app's own with.
///
///   dart run dart_not_native:font_widths --family Inter \
///       --regular assets/fonts/Inter-Regular.ttf \
///       --bold assets/fonts/Inter-Bold.ttf \
///       --out lib/inter_widths.dart
///
/// The file it writes has each character's advance width, regular and bold,
/// in thousandths of an em, the kerning pairs of printable ASCII, and a
/// `register<Family>()` that hands them to `TextPainter.registerFont` - call
/// it once in `main`. Without `--bold` the regular widths stand for both.
library;

import 'dart:io';

import 'package:dart_not_native/src/font_reader.dart';

void main(List<String> args) {
  String? option(String name) {
    final at = args.indexOf('--$name');
    return at >= 0 && at + 1 < args.length ? args[at + 1] : null;
  }

  final family = option('family');
  final regularPath = option('regular');
  if (family == null || regularPath == null) {
    stderr.writeln(
      'usage: dart run dart_not_native:font_widths --family <name> '
      '--regular <file.ttf> [--bold <file.ttf>] [--out <file.dart>]',
    );
    exit(2);
  }
  final boldPath = option('bold');
  final out = option('out') ?? 'lib/${_snake(family)}_widths.dart';
  final regular = FontReader(File(regularPath).readAsBytesSync());
  final bold = boldPath == null
      ? regular
      : FontReader(File(boldPath).readAsBytesSync());

  final name = _camel(family);
  final buffer = StringBuffer('''
// GENERATED by `dart run dart_not_native:font_widths` from
// ${regularPath.split('/').last}${boldPath == null ? '' : ' and ${boldPath.split('/').last}'} - do not edit by hand.
import 'package:dart_not_native/widgets.dart';

/// Measures text in `$family` with its own widths: call once, in `main`.
void register${name[0].toUpperCase()}${name.substring(1)}() =>
    TextPainter.registerFont(
      '$family',
      widths: _widths,
      kerning: _kerning,
      boldKerning: _boldKerning,
    );

// dart format off
const List<(int, List<int>, List<int>)> _widths = [
''');
  // Runs of the characters the font has, a short gap kept inside a run.
  final points = {...regular.codePoints, ...bold.codePoints}
      .where((c) => c <= 0xFFFF)
      .toList()
    ..sort();
  var i = 0;
  while (i < points.length) {
    final start = points[i];
    var end = start;
    while (i + 1 < points.length && points[i + 1] - end <= 8) {
      end = points[++i];
    }
    i++;
    buffer
      ..writeln('  (0x${start.toRadixString(16)},')
      ..writeln('    ${_list([for (var c = start; c <= end; c++) regular.width(c)])},')
      ..writeln('    ${_list([for (var c = start; c <= end; c++) bold.width(c)])}),');
  }
  buffer.writeln('];');
  for (final (title, font) in [('_kerning', regular), ('_boldKerning', bold)]) {
    buffer.writeln('const Map<int, int> $title = {');
    for (var left = 0x20; left < 0x7F; left++) {
      for (var right = 0x20; right < 0x7F; right++) {
        final kern = font.kern(left, right);
        if (kern != 0) {
          buffer.writeln('  0x${(left << 16 | right).toRadixString(16)}: $kern,');
        }
      }
    }
    buffer.writeln('};');
  }
  buffer.writeln('// dart format on');
  File(out).writeAsStringSync(buffer.toString());
  stdout.writeln('Wrote $out - call register${name[0].toUpperCase()}${name.substring(1)}() in main.');
}

String _list(List<int> values) => '[${values.join(', ')}]';

/// [family] as a Dart name: `Open Sans` is `openSans`.
String _camel(String family) {
  final words = family
      .split(RegExp(r'[^A-Za-z0-9]+'))
      .where((w) => w.isNotEmpty)
      .toList();
  if (words.isEmpty) return 'font';
  return [
    words.first.toLowerCase(),
    for (final w in words.skip(1)) w[0].toUpperCase() + w.substring(1).toLowerCase(),
  ].join();
}

String _snake(String family) => family
    .split(RegExp(r'[^A-Za-z0-9]+'))
    .where((w) => w.isNotEmpty)
    .map((w) => w.toLowerCase())
    .join('_');
