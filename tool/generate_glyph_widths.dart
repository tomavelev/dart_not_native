/// Regenerates the glyph width tables `TextPainter` measures with, from the
/// Roboto files the Flutter SDK caches and the Noto files the Android SDK's
/// API 22 platform ships.
///
///   dart tool/generate_glyph_widths.dart [path/to/flutter] [path/to/android-sdk]
///
/// Roboto is the font Android and a Flutter app draw Latin, Greek and
/// Cyrillic in, and Noto the one Android falls back to for Hebrew, Arabic,
/// Devanagari, Bengali, Tamil and Thai, so a string measured with their
/// advance widths is the width Android draws it at; iOS and a browser come
/// out within a few per cent. Two weights are taken - regular, and bold for
/// anything from 600 up. The widths are read from each file's `hmtx` table
/// through its Unicode `cmap`, in thousandths of an em. An Arabic letter is
/// measured in its isolated form: joined, most are narrower.
library;

import 'dart:io';
import 'dart:typed_data';

/// The code points measured in Roboto: Latin with its supplements and
/// extensions, Greek, Cyrillic, general punctuation and currency signs.
const _ranges = [
  (0x20, 0x24F),
  (0x300, 0x36F),
  (0x370, 0x3FF),
  (0x400, 0x4FF),
  (0x2000, 0x206F),
  (0x20A0, 0x20BF),
];

/// The scripts measured in Noto: the code points, and the family's file name
/// under the platform's `data/fonts`.
const _notoRanges = [
  (0x590, 0x5FF, 'NotoSansHebrew'),
  (0x600, 0x6FF, 'NotoNaskh'),
  (0x900, 0x97F, 'NotoSansDevanagari'),
  (0x980, 0x9FF, 'NotoSansBengali'),
  (0xB80, 0xBFF, 'NotoSansTamil'),
  (0xE00, 0xE7F, 'NotoSansThai'),
];

void main(List<String> args) {
  final flutterRoot = args.isNotEmpty ? args.first : _flutterRootFromPath();
  final androidSdk = args.length > 1
      ? args[1]
      : Platform.environment['ANDROID_HOME'] ??
            '${Platform.environment['HOME']}/Library/Android/sdk';
  final noto = '$androidSdk/platforms/android-22/data/fonts';
  final fonts = '$flutterRoot/bin/cache/artifacts/material_fonts';
  final regular = File('$fonts/Roboto-Regular.ttf');
  final bold = File('$fonts/Roboto-Bold.ttf');
  if (!regular.existsSync() || !bold.existsSync()) {
    stderr.writeln(
      'No Roboto under $fonts - run `flutter precache` or pass '
      'the SDK path.',
    );
    exit(2);
  }
  final light = _Font(regular.readAsBytesSync());
  final heavy = _Font(bold.readAsBytesSync());

  final buffer = StringBuffer('''
/// GENERATED by tool/generate_glyph_widths.dart - do not edit by hand.
///
/// How wide each character is in Roboto - the font Android and a Flutter app
/// draw text in - and, for Hebrew, Arabic, Devanagari, Bengali, Tamil and
/// Thai, in the Noto font Android draws those in; regular and bold, in
/// thousandths of an em: what `TextPainter` measures a string with. Read
/// from the font files the Flutter SDK caches and the Android SDK ships. A
/// character with no glyph is -1; a mark that takes no room is 0.
library;

/// Runs of code points from `start`, each with its regular and its bold
/// widths.
// dart format off
const List<(int, List<int>, List<int>)> glyphWidthRuns = [
''');
  void run(int start, int end, _Font light, _Font heavy) {
    final regularWidths = <int>[];
    final boldWidths = <int>[];
    for (var rune = start; rune <= end; rune++) {
      regularWidths.add(light.width(rune));
      boldWidths.add(heavy.width(rune));
    }
    buffer
      ..writeln('  (')
      ..writeln('    0x${start.toRadixString(16).toUpperCase()},')
      ..write(_list(regularWidths))
      ..write(_list(boldWidths))
      ..writeln('  ),');
  }

  for (final (start, end) in _ranges) {
    run(start, end, light, heavy);
  }
  for (final (start, end, family) in _notoRanges) {
    final regularFile = File('$noto/$family-Regular.ttf');
    final boldFile = File('$noto/$family-Bold.ttf');
    if (!regularFile.existsSync() || !boldFile.existsSync()) {
      stderr.writeln(
        'No $family under $noto - install the Android SDK platform '
        'android-22, or pass the SDK path.',
      );
      exit(2);
    }
    run(
      start,
      end,
      _Font(regularFile.readAsBytesSync()),
      _Font(boldFile.readAsBytesSync()),
    );
  }
  buffer
    ..writeln('];')
    ..writeln('// dart format on');
  final out = File('packages/native_bridge/lib/src/glyph_widths.dart');
  out.writeAsStringSync(buffer.toString());
  stdout.writeln('Wrote ${out.path}');
}

/// [widths] as a list literal, as many to a line as fit in 80 columns.
String _list(List<int> widths) {
  final out = StringBuffer('    [\n');
  var line = StringBuffer('     ');
  for (final width in widths) {
    final item = ' $width,';
    if (line.length + item.length > 80) {
      out.writeln(line);
      line = StringBuffer('     ');
    }
    line.write(item);
  }
  out
    ..writeln(line)
    ..writeln('    ],');
  return out.toString();
}

/// The parts of a TrueType file a width is read from.
class _Font {
  _Font(Uint8List bytes) : _data = ByteData.sublistView(bytes) {
    final tables = _data.getUint16(4);
    for (var i = 0; i < tables; i++) {
      final at = 12 + i * 16;
      final tag = String.fromCharCodes(bytes.sublist(at, at + 4));
      _tables[tag] = _data.getUint32(at + 8);
    }
    _unitsPerEm = _data.getUint16(_tables['head']! + 18);
    _metrics = _data.getUint16(_tables['hhea']! + 34);
    _readCmap();
  }

  final ByteData _data;
  final Map<String, int> _tables = {};
  late final int _unitsPerEm;
  late final int _metrics;
  final Map<int, int> _glyphs = {};

  /// How wide [rune] is, in thousandths of an em; -1 with no glyph for it.
  int width(int rune) {
    final glyph = _glyphs[rune];
    if (glyph == null || glyph == 0) return -1;
    final index = glyph < _metrics ? glyph : _metrics - 1;
    final advance = _data.getUint16(_tables['hmtx']! + index * 4);
    return (advance * 1000 / _unitsPerEm).round();
  }

  /// The Unicode BMP subtable (platform 3, encoding 1; format 4).
  void _readCmap() {
    final cmap = _tables['cmap']!;
    final count = _data.getUint16(cmap + 2);
    int? table;
    for (var i = 0; i < count; i++) {
      final at = cmap + 4 + i * 8;
      if (_data.getUint16(at) == 3 && _data.getUint16(at + 2) == 1) {
        table = cmap + _data.getUint32(at + 4);
      }
    }
    if (table == null || _data.getUint16(table) != 4) {
      throw StateError('no Unicode format-4 cmap');
    }
    final segments = _data.getUint16(table + 6) ~/ 2;
    final ends = table + 14;
    final starts = ends + segments * 2 + 2;
    final deltas = starts + segments * 2;
    final offsets = deltas + segments * 2;
    for (var s = 0; s < segments; s++) {
      final end = _data.getUint16(ends + s * 2);
      final start = _data.getUint16(starts + s * 2);
      final delta = _data.getInt16(deltas + s * 2);
      final offsetAt = offsets + s * 2;
      final offset = _data.getUint16(offsetAt);
      for (var rune = start; rune <= end && rune != 0xFFFF; rune++) {
        int glyph;
        if (offset == 0) {
          glyph = (rune + delta) & 0xFFFF;
        } else {
          final at = offsetAt + offset + (rune - start) * 2;
          glyph = _data.getUint16(at);
          if (glyph != 0) glyph = (glyph + delta) & 0xFFFF;
        }
        _glyphs[rune] = glyph;
      }
    }
  }
}

String _flutterRootFromPath() {
  final flutter = Process.runSync('which', ['flutter']).stdout as String;
  final bin = File(flutter.trim()).resolveSymbolicLinksSync();
  return Directory(bin).parent.parent.path;
}
